export function isCorrectionSignTask(task: {title:string;requirement:string}) {
  return /订签|订正[\s\S]{0,35}(?:签字|签名)|(?:签字|签名)[\s\S]{0,35}订正/u.test(`${task.title} ${task.requirement}`);
}
